function makeGuide(city: MetroName, district: string, zones: string[]): LocalGuide {
  const note = cityNotes[city];
  const zoneText = zones.join("·");
  return {
    localIntro: `${city} ${district}는 ${zoneText} 생활권의 주거·도로 조건이 서로 다릅니다. ${note.intro}`,
    localChecklist: [
      `${zones[0]} 생활권의 공동주택 이사시간·엘리베이터 예약 확인`,
      `${zones[1] ?? zones[0]}의 주차 위치와 이사차량 진입 조건 확인`,
      `${zones[2] ?? zones[0]}의 골목·외곽·산업도로 조건 확인`,
      note.traffic
    ],
    movingNote: `${district} 이사는 같은 구·군 안에서도 생활권에 따라 차량 접근, 운반거리, 엘리베이터 사용조건이 달라질 수 있습니다. 출발지와 도착지 사진과 관리규정을 업체에 미리 전달하는 것이 좋습니다.`,
    officeNote: note.office,
    neighborhoods: zones.map((name, i) => ({
      name,
      note: i === 0 ? `${name}은 공동주택·상권 비중을 고려해 관리규정과 주차조건을 먼저 확인하는 것이 좋습니다.` : i === 1 ? `${name}은 건물 형태와 도로 폭에 따라 차량 위치와 운반거리가 달라질 수 있습니다.` : `${name}은 외곽·산업·경사지 등 지역 여건을 확인해 차량 진입과 이동시간을 계획하세요.`,
      tags: i === 0 ? ["공동주택","관리규정","주차"] : i === 1 ? ["차량접근","운반거리","도로조건"] : ["지역특성","이동시간","현장확인"]
    }))
  };
}

export function getMetroGuide(city: string, district: string): LocalGuide | undefined {
  if (!(city in areas)) return undefined;
  const metro = city as MetroName;
  const zones = areas[metro][district];
  return zones ? makeGuide(metro, district, zones) : undefined;
}
